pub async fn recreate_env(
    tool: &str,
    tx: mpsc::UnboundedSender<String>,
) -> Result<(), String> {
    match tool.to_lowercase().as_str() {
        "cadence" => {
            write_file(CADENCE_ENV_FILE, CADENCE_ENV_SCRIPT, 0o644)?;
            send_log(&tx, &format!("[SUCCESS] Wrote {}", CADENCE_ENV_FILE));
        }
        // Xilinx, Silvaco and CADRE are defined entirely inside the shared
        // eda-launcher.sh (lazy loader / always-loaded PATH respectively) —
        // there is no separate per-tool file to regenerate for them.
        "xilinx" | "silvaco" | "cadre" => {}
        _ => return Err(format!("Unknown tool: {}", tool)),
    }

    write_base_launcher(&tx)?;
    send_log(&tx, &format!("[SUCCESS] Refreshed environment for {}", tool));
    Ok(())
}

fn write_base_launcher(tx: &mpsc::UnboundedSender<String>) -> Result<(), String> {
    write_file(EDA_LAUNCHER, EDA_LAUNCHER_SCRIPT, 0o755)?;
    send_log(tx, "[SUCCESS] Refreshed base eda-launcher.sh");
    Ok(())
}

fn write_file(path: &str, contents: &str, mode: u32) -> Result<(), String> {
    if let Some(parent) = Path::new(path).parent() {
        fs::create_dir_all(parent).map_err(|e| format!("Failed to create {}: {}", parent.display(), e))?;
    }
    fs::write(path, contents).map_err(|e| format!("Failed to write {}: {}", path, e))?;
    use std::os::unix::fs::PermissionsExt;
    let _ = fs::set_permissions(path, fs::Permissions::from_mode(mode));
    Ok(())
}

fn send_log(tx: &mpsc::UnboundedSender<String>, msg: &str) {
    tx.send(msg.to_string()).ok();
}
